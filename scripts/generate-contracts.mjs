import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "packages/shared/src/contracts/contracts.ts");
const outDir = dirname(outFile);

mkdirSync(outDir, { recursive: true });

function run(cmd, args, opts = {}) {
  const result = spawnSync(cmd, args, {
    stdio: "inherit",
    cwd: root,
    shell: process.platform === "win32",
    ...opts
  });
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
}

const typeshare = spawnSync("typeshare", ["--help"], { cwd: root, encoding: "utf8" });
if (typeshare.status !== 0) {
  console.error("typeshare CLI not found. Install with: cargo install typeshare-cli --locked");
  process.exit(1);
}

run("typeshare", [
  "src-tauri/src",
  "--config-file",
  "typeshare.toml",
  "--lang",
  "typescript",
  "--output-file",
  outFile
]);

let ts = readFileSync(outFile, "utf8");
if (!ts.includes("export type Value")) {
  ts = ts.replace(
    /(\/\*\n Generated by typeshare[^\n]*\n\*\/\n)/,
    `$1\n/** JSON value from Rust \`serde_json::Value\` (typeshare placeholder). */\nexport type Value = unknown;\n`
  );
  writeFileSync(outFile, ts);
}

run("pnpm", ["prettier", "--write", outFile]);

console.log(`wrote ${outFile}`);
